z=int(input("Введіть ЗП: "))
s=int(input("Введіть стаж роботи: "))

if 0 <= s < 1:
    print("Премія не передбачена!")
elif 1 <= s < 3:
    print(f"Премія 5% від зарплати, тобто {z/100*5}грн")
elif 3 <= s < 5:
    print(f"Премія 10% від зарплати, тобто {z / 100 * 10}грн")
elif s > 5:
    print(f"Премія 15% від зарплати, тобто {z / 100 * 15}грн")
else:
    print("Некоректні дані!")